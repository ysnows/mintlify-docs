#!/usr/bin/env node
// Rebuilds docs.json navigation.languages: the English navigation as it is, plus one entry per enabled language,
// generated from the English navigation and i18n/nav/<code>.json. Also writes the stub pages that send
// keepEnglish entries to the English page. Run it after the English navigation or the translations change.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, config, enabledLanguages, readDocs, englishNav, targetFile, sourceFile } from './i18n-lib.mjs';

const docs = readDocs();
const en = englishNav(docs);
const topNavbar = docs.navbar;
const missing = [];

const title = (file) => {
  const m = fs.readFileSync(file, 'utf8').match(/^title:\s*["']?(.*?)["']?\s*$/m);
  return m ? m[1] : path.basename(file, '.mdx');
};

function stub(l, labels, page) {
  const t = (fs.existsSync(targetFile(l, page)) && !fs.readFileSync(targetFile(l, page), 'utf8').includes('i18n-stub')) ? null : (labels.pageTitles?.[page] ?? title(sourceFile(page)));
  if (t === null) return; // a real translation exists; leave it
  const body = `---\ntitle: "${t}${labels.keepEnglishSuffix}"\ndescription: "${labels.keepEnglishNote}"\nurl: "/${page}"\n---\n\n{/* i18n-stub: generated by scripts/i18n-nav.mjs, links to the English page */}\n\n${labels.keepEnglishNote} [${labels.keepEnglishLink}](/${page})\n`;
  fs.mkdirSync(path.dirname(targetFile(l, page)), { recursive: true });
  fs.writeFileSync(targetFile(l, page), body);
}

function translateNode(node, l, labels) {
  if (typeof node === 'string') {
    if (config.keepEnglish.includes(node)) stub(l, labels, node);
    else if (!fs.existsSync(targetFile(l, node))) { missing.push(node); return null; }
    return `${l.dir}/${node}`;
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === 'tab') out.tab = labels.tabs?.[v] ?? v;
    else if (k === 'group') out.group = labels.groups?.[v] ?? v;
    else if (k === 'anchor') out.anchor = labels.anchors?.[v] ?? v;
    else if (k === 'root' && typeof v === 'string') out.root = `${l.dir}/${v}`;
    else if (['tabs', 'groups', 'pages', 'anchors'].includes(k) && Array.isArray(v)) out[k] = v.map((c) => translateNode(c, l, labels)).filter((c) => c !== null);
    else if (k === 'global') out.global = translateNode(v, l, labels);
    else out[k] = v;
  }
  if (out.pages && out.pages.length === 0) return null;
  if (out.groups) out.groups = out.groups.filter(Boolean);
  return out;
}

function translateNavbar(navbar, labels) {
  if (!navbar) return undefined;
  const n = JSON.parse(JSON.stringify(navbar));
  for (const link of n.links ?? []) link.label = labels.navbar?.[link.label] ?? link.label;
  if (n.primary?.label) n.primary.label = labels.navbar?.[n.primary.label] ?? n.primary.label;
  return n;
}

const languages = [{ language: config.source, ...en }];
for (const l of enabledLanguages()) {
  const labels = JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n/nav', `${l.code}.json`), 'utf8'));
  const entry = translateNode(en, l, labels);
  languages.push({ language: l.code, navbar: translateNavbar(topNavbar, labels), ...entry });
}
docs.navigation = { languages };
fs.writeFileSync(path.join(ROOT, 'docs.json'), JSON.stringify(docs, null, 2) + '\n');
if (missing.length) console.log(`Left out of the navigation until translated (${missing.length}):\n  ${[...new Set(missing)].join('\n  ')}`);
console.log(`docs.json navigation: ${languages.map((x) => x.language).join(', ')}`);
